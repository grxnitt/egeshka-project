-- Reviews written on the site (reviews_service), stored only on the Russian server.
--
-- Identity is an email confirmed by a one-time code; the database keeps only a keyed hash of it (users.email_hash),
-- never the address. Two separate login roles:
--   reviews_public  - the site API: may create PENDING, UNVERIFIED site reviews and delete a person's own data;
--                     cannot approve, cannot mark verified, cannot touch Telegram users or bot reviews.
--   reviews_admin   - the moderation console (localhost only, behind SSH): approves, rejects, deletes site reviews.
-- Login roles and passwords are created on the server, never in Git.

-- 1. A person can be known by Telegram (bot) or by a confirmed email (site).
alter table public.users alter column telegram_id drop not null;
alter table public.users add column if not exists email_hash varchar(64);
create unique index if not exists users_email_hash_key on public.users (email_hash) where email_hash is not null;
alter table public.users drop constraint if exists users_identity_check;
alter table public.users add constraint users_identity_check check (telegram_id is not null or email_hash is not null);
alter table public.users alter column consent_version type varchar(40);

-- 2. Review fields for the site.
alter table public.reviews add column if not exists source varchar(10) not null default 'bot';
alter table public.reviews drop constraint if exists reviews_source_check;
alter table public.reviews add constraint reviews_source_check check (source in ('bot', 'site'));
alter table public.reviews add column if not exists study_period varchar(20);
alter table public.reviews drop constraint if exists reviews_study_period_check;
alter table public.reviews add constraint reviews_study_period_check
  check (study_period is null or study_period in ('2026/27', '2025/26', '2024/25', 'earlier'));
alter table public.reviews add column if not exists ip_hash varchar(64);          -- cleared at moderation
alter table public.reviews add column if not exists moderated_at timestamp with time zone;
alter table public.reviews add column if not exists consent_version varchar(40);
create index if not exists reviews_pending_site_idx on public.reviews (created_at) where moderation_status = 'pending' and source = 'site';
create index if not exists reviews_ip_hash_idx on public.reviews (ip_hash) where ip_hash is not null;

-- 3. Unconfirmed drafts, screenshots, deletion requests. Plain "timestamp" (UTC) like the service writes it.
create table if not exists public.review_drafts (
  id integer generated by default as identity primary key,
  token_hash varchar(64) not null unique,
  email_hash varchar(64) not null,
  code_hash varchar(64) not null,
  attempts integer not null default 0,
  resends integer not null default 0,
  last_sent_at timestamp not null,
  payload text not null check (char_length(payload) <= 20000),
  ip_hash varchar(64) not null default '',
  expires_at timestamp not null,
  created_at timestamp not null default (now() at time zone 'utc')
);
create index if not exists review_drafts_email_hash_idx on public.review_drafts (email_hash);
create index if not exists review_drafts_expires_at_idx on public.review_drafts (expires_at);

create table if not exists public.review_proofs (
  id integer generated by default as identity primary key,
  review_id integer references public.reviews(id) on delete cascade,
  draft_id integer references public.review_drafts(id) on delete cascade,
  file_name varchar(80) not null unique check (file_name ~ '^[0-9a-f]{40}\.webp$'),
  width integer not null,
  height integer not null,
  bytes integer not null,
  created_at timestamp not null default (now() at time zone 'utc'),
  check ((review_id is null) <> (draft_id is null))
);
create index if not exists review_proofs_review_id_idx on public.review_proofs (review_id);
create index if not exists review_proofs_draft_id_idx on public.review_proofs (draft_id);

create table if not exists public.deletion_requests (
  id integer generated by default as identity primary key,
  token_hash varchar(64) not null unique,
  email_hash varchar(64) not null,
  code_hash varchar(64) not null,
  attempts integer not null default 0,
  expires_at timestamp not null,
  created_at timestamp not null default (now() at time zone 'utc')
);

alter table public.review_drafts enable row level security;
alter table public.review_proofs enable row level security;
alter table public.deletion_requests enable row level security;
revoke all on public.review_drafts, public.review_proofs, public.deletion_requests from anon, authenticated;

-- 4. Roles.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'reviews_public') then create role reviews_public nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'reviews_admin') then create role reviews_admin nologin; end if;
end $$;
grant usage on schema public to reviews_public, reviews_admin;
grant usage, select on all sequences in schema public to reviews_public, reviews_admin;

grant select on public.schools, public.teachers to reviews_public, reviews_admin;
drop policy if exists schools_reviews_read on public.schools;
create policy schools_reviews_read on public.schools for select to reviews_public, reviews_admin using (true);
drop policy if exists teachers_reviews_read on public.teachers;
create policy teachers_reviews_read on public.teachers for select to reviews_public, reviews_admin using (true);

-- users: only email identities, never Telegram users
grant select, insert, update (consent_at, consent_version), delete on public.users to reviews_public;
grant select, delete on public.users to reviews_admin;
drop policy if exists users_site_public on public.users;
create policy users_site_public on public.users for all to reviews_public
  using (telegram_id is null and email_hash is not null) with check (telegram_id is null and email_hash is not null);
drop policy if exists users_site_admin on public.users;
create policy users_site_admin on public.users for all to reviews_admin using (telegram_id is null);

-- reviews: the public role inserts only pending, unverified site reviews; it has no UPDATE at all
grant select, insert, delete on public.reviews to reviews_public;
grant select, update (moderation_status, verified, moderated_at, ip_hash), delete on public.reviews to reviews_admin;
drop policy if exists reviews_site_public_read on public.reviews;
create policy reviews_site_public_read on public.reviews for select to reviews_public using (source = 'site');
drop policy if exists reviews_site_public_insert on public.reviews;
create policy reviews_site_public_insert on public.reviews for insert to reviews_public
  with check (source = 'site' and moderation_status = 'pending' and verified = false and moderated_at is null);
drop policy if exists reviews_site_public_delete on public.reviews;
create policy reviews_site_public_delete on public.reviews for delete to reviews_public using (source = 'site');
drop policy if exists reviews_site_admin on public.reviews;
create policy reviews_site_admin on public.reviews for all to reviews_admin using (source = 'site') with check (source = 'site');

grant select, insert, delete on public.review_criterion_scores to reviews_public;
grant select, delete on public.review_criterion_scores to reviews_admin;
drop policy if exists review_scores_site on public.review_criterion_scores;
create policy review_scores_site on public.review_criterion_scores for all to reviews_public, reviews_admin
  using (exists (select 1 from public.reviews r where r.id = review_id and r.source = 'site'))
  with check (exists (select 1 from public.reviews r where r.id = review_id and r.source = 'site'));

grant select, insert, update, delete on public.review_drafts, public.deletion_requests to reviews_public;
grant select, insert, update (review_id, draft_id), delete on public.review_proofs to reviews_public;
grant select, delete on public.review_proofs to reviews_admin;
drop policy if exists review_drafts_public on public.review_drafts;
create policy review_drafts_public on public.review_drafts for all to reviews_public using (true) with check (true);
drop policy if exists deletion_requests_public on public.deletion_requests;
create policy deletion_requests_public on public.deletion_requests for all to reviews_public using (true) with check (true);
drop policy if exists review_proofs_site on public.review_proofs;
create policy review_proofs_site on public.review_proofs for all to reviews_public, reviews_admin using (true) with check (true);

grant execute on function public.refresh_all_rating_snapshots() to reviews_public, reviews_admin;

-- 5. The public list of reviews shows when the author studied and where the review came from.
create or replace view public.public_reviews as
select
  r.id, r.school_id, r.teacher_id, r.criterion, r.criteria_json, r.score, r.text_positive, r.text_negative,
  r.verified, r.created_at, r.study_period, r.source
from public.reviews r
where r.moderation_status = 'approved';
grant select on public.public_reviews to anon, authenticated;
