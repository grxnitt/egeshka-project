-- Console tools: audit log, block list, editable editorial scores with history, public live view of the scores.
-- Roles: reviews_admin (the console), reviews_public (the review form reads the block list), anon (reads the public view).

-- 1. Editorial scores can be edited in the console; the date of the last check feeds the monthly review.
alter table public.schools add column if not exists scores_reviewed_at timestamp;

create table if not exists public.school_score_history (
  id integer generated by default as identity primary key,
  school_id integer not null references public.schools(id) on delete cascade,
  at timestamp not null default (now() at time zone 'utc'),
  reason varchar(500) not null,
  changes text not null default '{}'
);
create index if not exists school_score_history_school_idx on public.school_score_history (school_id, at desc);

-- 2. What was done in the console, and when.
create table if not exists public.admin_log (
  id integer generated by default as identity primary key,
  at timestamp not null default (now() at time zone 'utc'),
  action varchar(60) not null,
  target varchar(120) not null default '',
  detail varchar(500) not null default ''
);
create index if not exists admin_log_at_idx on public.admin_log (at desc);

-- 3. Block list: keyed hashes of an email or a network (never the plain values).
create table if not exists public.blocked (
  id integer generated by default as identity primary key,
  kind varchar(10) not null check (kind in ('email', 'ip')),
  value varchar(64) not null,
  reason varchar(200) not null default '',
  created_at timestamp not null default (now() at time zone 'utc'),
  unique (kind, value)
);

alter table public.school_score_history enable row level security;
alter table public.admin_log enable row level security;
alter table public.blocked enable row level security;
revoke all on public.school_score_history, public.admin_log, public.blocked from anon, authenticated;

grant select, insert on public.school_score_history, public.admin_log to reviews_admin;
grant select, insert, delete on public.blocked to reviews_admin;
grant select on public.blocked to reviews_public;
grant usage, select on all sequences in schema public to reviews_admin, reviews_public;

drop policy if exists score_history_admin on public.school_score_history;
create policy score_history_admin on public.school_score_history for all to reviews_admin using (true) with check (true);
drop policy if exists admin_log_admin on public.admin_log;
create policy admin_log_admin on public.admin_log for all to reviews_admin using (true) with check (true);
drop policy if exists blocked_admin on public.blocked;
create policy blocked_admin on public.blocked for all to reviews_admin using (true) with check (true);
drop policy if exists blocked_public_read on public.blocked;
create policy blocked_public_read on public.blocked for select to reviews_public using (true);

-- The console may change only the editorial score columns of a school, nothing else.
grant update (teachers_score, practice_score, feedback_score, curator_score, platform_score, workload_score,
              price_quality_score, criteria_status, scores_reviewed_at) on public.schools to reviews_admin;
drop policy if exists schools_admin_update on public.schools;
create policy schools_admin_update on public.schools for update to reviews_admin using (true) with check (true);

-- 4. Live scores for the site: the pages overwrite the numbers baked into the static files with these.
create or replace view public.school_scores_public as
select
  s.id as school_id,
  s.teachers_score, s.practice_score, s.feedback_score, s.curator_score, s.platform_score, s.workload_score,
  s.price_quality_score as organization_score,
  s.criteria_status,
  s.scores_reviewed_at
from public.schools s
where s.is_active;
grant select on public.school_scores_public to anon, authenticated;
