"""Turn research notes into concise teacher-facing profile copy."""

import re


_PREFIXES = (
    r"^Официальный каталог(?: Умскула)?:\s*",
    r"^Официальная страница(?: ЕГЭ(?:-2027)?)?:\s*",
    r"^Официальный профиль(?: [^:]+)?:\s*",
    r"^Профиль школы(?: и (?:Telegram|Телеграм)[-‑]канал(?: [^:]+)?| и канал)?:\s*",
)


def teacher_description(text: str) -> str:
    """Remove provenance labels while preserving useful facts and caveats."""
    value = text.strip()
    for pattern in _PREFIXES:
        value = re.sub(pattern, "", value, flags=re.IGNORECASE)

    replacements = (
        (r"В подтверждённом Telegram-канале регулярно выходят\s+", "Публикует "),
        (r"В подтверждённом Telegram-канале\s*[—-]\s*", "Публикует "),
        (r"Подтверждённый Telegram-канал публикует\s+", "Публикует "),
        (r"В официальном Telegram-канале преподаватель публикует\s+", "Публикует "),
        (r"В Telegram[-‑]канале преподаватель дополнительно заявляет\s+", "Также заявляет "),
        (r"В Telegram[-‑]канале преподаватель также заявляет\s+", "Также заявляет "),
        (r"В Telegram[-‑]канале преподаватель заявляет\s+", "Заявляет "),
        (r"В Telegram[-‑]канале также указаны\s+", "Также указаны "),
        (r"В публичном Telegram-канале преподаватель также заявляет\s+", "Также заявляет "),
        (r"В Telegram[-‑]канале преподаватель также заявляет, что\s+", "Заявляет, что "),
        (r"В Telegram[-‑]канале преподаватель указывает\s+", "Указывает "),
        (r"В публичном канале школы встречаются репосты его авторских разборов\s+", "Публикует авторские разборы "),
        (r"Подтверждённый Telegram-канал использует\s+", "Использует "),
        (r"Подтверждённый Telegram-канал ведёт новости, общение и\s+", "Публикует "),
        (r"Официальный профиль 99 Баллов заявляет\s+", ""),
        (r"канал заявляет, что\s+", "заявляет, что "),
        (r"канал заявляет\s+", "заявлены "),
        (r"В канале также указано\s+", "Также указано "),
        (r"Канал профильной математики подтверждён со страницы преподавателя\.\s*", ""),
        (r"Ведёт открытый предметный Telegram-канал\.\s*", "Публикует материалы и разборы по предмету. "),
        (r"по данным официального (?:сайта|профиля)", ""),
        (r"по официальному каталогу Skysmart", "в Skysmart"),
        (r"в официальном каталоге Вебиума", "в Вебиуме"),
        (r"Официальный сайт заявляет\s+", ""),
        (r"официальный профиль сообщает о\s+", ""),
        (r"школа (?:указывает|заявляет)\s+", ""),
        (r"Школа (?:указывает|заявляет)\s+", ""),
        (r";?\s*показатели опубликованы школой(?:/преподавателем)?\.\s*", ". "),
        (r";?\s*результаты — заявления школы/преподавателя\.\s*", ". "),
        (r";?\s*это материалы преподавателя/школы\.\s*", ". "),
        (r";?\s*это заявленные преподавателем показатели\.\s*", ". "),
        (r";?\s*цифры относятся к заявлениям преподавателя\.\s*", ". "),
        (r";?\s*цифры являются самозаявленными\.\s*", ". "),
        (r";?\s*Это самозаявленные показатели\.\s*", ". "),
    )
    for pattern, replacement in replacements:
        value = re.sub(pattern, replacement, value, flags=re.IGNORECASE)

    value = re.sub(
        r"^Профиль школы и представление в канале 100Б:\s*",
        "",
        value,
        flags=re.IGNORECASE,
    )
    value = value.replace(
        "профиль школы также указывает более 2 000 школьников. Цифры расходятся по датам и требуют уточнения.",
        "в другой публикации указано более 2 000 школьников. Число учеников расходится по датам.",
    )
    value = value.replace(
        "Публикует конспекты, тесты, открытые вебинары и теория.",
        "Публикует конспекты, тесты, открытые вебинары и теорию.",
    )
    value = re.sub(
        r"^Официальная карточка преподавателя биологии:\s*",
        "Преподаёт биологию: ",
        value,
        flags=re.IGNORECASE,
    )
    value = re.sub(
        r"^Официальная карточка преподавателя биологии в каталоге Сотки\.$",
        "Преподаёт биологию в Сотке.",
        value,
        flags=re.IGNORECASE,
    )

    value = re.sub(r"\s+", " ", value).strip()
    value = re.sub(r"\s+([,.;])", r"\1", value)
    value = re.sub(r"\.\s*\.", ".", value)
    if value:
        value = value[0].upper() + value[1:]
    return value
